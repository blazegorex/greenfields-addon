"""Turns downloaded painted art into WoW textures and regenerates Greenfields/Data/Art.lua.

    python tools/import_art.py            # process every PNG in tools/art/downloads/

Drop generated PNGs into tools/art/downloads/ named by their manifest id
(tools/art/manifest.json), e.g. hero_raids.png, title_deaths_raid.png, crest.png.
Each is cropped/resized to a power-of-two TGA in Greenfields/Media/art/ and listed in
Data/Art.lua, which the UI reads at load: anything listed shows up, anything missing falls
back to the built-in look. Re-run any time; it's idempotent.
"""
import json
import os
import sys

from PIL import Image, ImageFilter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_media  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, "tools", "art")
DOWNLOADS = os.path.join(ART, "downloads")
OUT_DIR = os.path.join(ROOT, "Greenfields", "Media", "art")
ART_LUA = os.path.join(ROOT, "Greenfields", "Data", "Art.lua")
GAME_PATH = "Interface\\\\AddOns\\\\Greenfields\\\\Media\\\\art\\\\"

SIZES = {"hero": (1024, 256), "header": (1024, 128), "crest": (256, 256), "title": (128, 128), "nav": (64, 64)}


def crop_to(img, w, h):
    """Centre-crop to the target aspect, then resize."""
    sw, sh = img.size
    target = w / h
    if sw / sh > target:
        nw = int(sh * target)
        x = (sw - nw) // 2
        img = img.crop((x, 0, x + nw, sh))
    else:
        nh = int(sw / target)
        y = (sh - nh) // 2
        img = img.crop((0, y, sw, y + nh))
    return img.resize((w, h), Image.LANCZOS)


def save(img, name):
    old = make_media.OUT
    make_media.OUT = OUT_DIR
    try:
        make_media.save_tga(img, name)
    finally:
        make_media.OUT = old


def main():
    manifest = json.load(open(os.path.join(ART, "manifest.json"), encoding="utf-8"))
    os.makedirs(OUT_DIR, exist_ok=True)
    found = {"heroes": {}, "titles": {}, "nav": {}, "header": None, "crest": None}
    for item in manifest["items"]:
        src = os.path.join(DOWNLOADS, item["id"] + ".png")
        if not os.path.exists(src):
            continue
        kind = item["kind"]
        img = Image.open(src).convert("RGBA")
        w, h = SIZES[kind]
        out = crop_to(img, w, h)
        if kind in ("title", "nav"):
            out = out.filter(ImageFilter.UnsharpMask(radius=1.2, percent=60, threshold=2))
        save(out, item["id"])
        path = GAME_PATH + item["id"]
        if kind == "hero":
            found["heroes"][item["page"]] = path
        elif kind == "title":
            found["titles"][item["stat"]] = path
        elif kind == "nav":
            found["nav"][item["page"]] = path
        else:
            found[kind] = path
        print("  %-28s -> Media/art/%s.tga (%dx%d)" % (os.path.basename(src), item["id"], w, h))

    def table(d):
        if not d:
            return "{}"
        rows = ",\n".join('        %s = "%s"' % (k, v) for k, v in sorted(d.items()))
        return "{\n" + rows + ",\n    }"

    lua = """--[[ Greenfields - Data/Art.lua
     GENERATED by tools/import_art.py - lists the painted art shipped in Media/art/.
     Empty tables mean "no custom art yet": the UI falls back to the built-in look.

       heroes[pageKey] = texture path   wide painted banner behind a page's header
       header          = texture path   painted strip behind the window header
       crest           = texture path   guild crest
       titles[statKey] = texture path   custom title icon (overrides the game icon)
       nav[pageKey]    = texture path   custom sidebar icon (overrides the game icon) ]]

local _, GF = ...

GF.Art = {
    heroes = %s,
    header = %s,
    crest = %s,
    titles = %s,
    nav = %s,
}
""" % (table(found["heroes"]), ('"%s"' % found["header"]) if found["header"] else "nil",
       ('"%s"' % found["crest"]) if found["crest"] else "nil", table(found["titles"]), table(found["nav"]))
    open(ART_LUA, "w", encoding="utf-8", newline="\n").write(lua)
    n = len(found["heroes"]) + len(found["titles"]) + len(found["nav"]) + bool(found["header"]) + bool(found["crest"])
    print("Data/Art.lua lists %d pieces of art." % n)


if __name__ == "__main__":
    main()
