"""The pixel-art look: builds the game's textures from the PixelLab art kept in tools/art/pixel/ and
writes Greenfields/Data/ArtFx.lua, the one-shot bursts UI/Motion.lua plays for a win or a yes.

    python -P tools/pixel_art.py

What's in tools/art/pixel/ (all PNG, made with PixelLab from the procedural art in Nov 2026; the
subscription's gone, so this folder is the source now, not something to regenerate):
    banners/<page>.png       800 x 112, the whole banner, both halves joined
    portraits/<stat>.png     Hall of Fame title icons, border already cut off
    crest.png, minimap.png
    vfx/<kind>.png           one-shot bursts (PixelLab's VFX), laid out as bursts.json says

Run this after tools/make_scenes.py: that one paints the old poster banners over these.
"""
import json
import math
import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_media  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "tools", "art", "pixel")
MEDIA = os.path.join(ROOT, "Greenfields", "Media")
ART_FX = os.path.join(ROOT, "Greenfields", "Data", "ArtFx.lua")
GAME = "Interface\\\\AddOns\\\\Greenfields\\\\Media\\\\art\\\\"


def save(img, name):
    old = make_media.OUT
    make_media.OUT = MEDIA
    try:
        make_media.save_tga(img, name)
    finally:
        make_media.OUT = old


def pow2(n):
    return 1 << max(4, math.ceil(math.log2(n)))


def lua_row(d):
    parts = []
    for k in ("tex", "cols", "frames", "cw", "ch", "fps"):
        v = d[k]
        parts.append('%s = %s' % (k, ('"%s"' % v) if isinstance(v, str) else repr(v)))
    return "{ " + ", ".join(parts) + " }"


def main():
    # banners
    for f in sorted(os.listdir(os.path.join(SRC, "banners"))):
        name = f[:-4]
        im = Image.open(os.path.join(SRC, "banners", f)).convert("RGBA")
        save(im.resize((2048, 256), Image.NEAREST), os.path.join("art", "hero_" + name))
    # portraits, crest and the minimap button
    for f in sorted(os.listdir(os.path.join(SRC, "portraits"))):
        im = Image.open(os.path.join(SRC, "portraits", f)).convert("RGBA")
        save(im.resize((128, 128), Image.NEAREST), os.path.join("art", "title_" + f[:-4]))
    save(Image.open(os.path.join(SRC, "crest.png")).convert("RGBA").resize((128, 128), Image.NEAREST), os.path.join("art", "crest"))
    save(Image.open(os.path.join(SRC, "minimap.png")).convert("RGBA").resize((64, 64), Image.NEAREST), "minimap")

    # the one-shot bursts: their sheets padded out to a power of two
    bursts = {}
    for kind, b in sorted(json.load(open(os.path.join(SRC, "vfx", "bursts.json"), encoding="utf-8")).items()):
        im = Image.open(os.path.join(SRC, "vfx", b["file"])).convert("RGBA")
        tw, th = pow2(im.width), pow2(im.height)
        sheet = Image.new("RGBA", (tw, th), (0, 0, 0, 0))
        sheet.paste(im, (0, 0))
        save(sheet, os.path.join("art", "burst_" + kind))
        bursts[kind] = {"tex": GAME + "burst_" + kind, "cols": b["cols"], "frames": b["frames"], "fps": b["fps"],
                        "cw": round(b["cell"] / tw, 6), "ch": round(b["cell"] / th, 6)}

    lua = """--[[ Greenfields - Data/ArtFx.lua
     GENERATED by tools/pixel_art.py - the one-shot bursts UI:Burst plays. Each is a flipbook
     sheet of `frames` cells, `cols` across, each cw x ch of the texture. ]]

local _, GF = ...

GF.ArtFx = {
    bursts = {
%s
    },
}
""" % "\n".join("        %s = %s," % (k, lua_row(v)) for k, v in sorted(bursts.items()))
    open(ART_FX, "w", encoding="utf-8", newline="\n").write(lua)
    print("banners, portraits, crest, minimap and %d bursts" % len(bursts))


if __name__ == "__main__":
    main()
