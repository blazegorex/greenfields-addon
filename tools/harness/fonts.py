"""Font mapping shared by render.py (system Python + PIL) and run.py (venv, no PIL).

The real game fonts are used when gamefiles\\fonts\\ holds them (extracted from this PC's own
WoW install by gamefiles\\extract.py, gitignored, never committed or shipped):
    FRIZQT__ -> frizqt.ttf, ARIALN -> arialn.ttf, MORPHEUS -> morpheus.ttf, SKURRI -> skurri.ttf

Other machines fall back to Windows stand-ins:
    FRIZQT__ -> georgia.ttf (falls back to segoeui.ttf)
    ARIALN   -> arialn.ttf if present, else arial.ttf drawn with narrower tracking
    MORPHEUS -> georgiab.ttf
    SKURRI   -> georgiab.ttf
Anything else falls back to FRIZQT.

`font_metrics.json` (generated by `render.py --metrics`) holds per-character advance
widths at size 100 for each font, so the mock's GetStringWidth matches what the
renderer draws. run.py loads it when present and otherwise uses a flat estimate. It is
generated from the real fonts on the owner's PC, so on a machine with only the stand-ins
the drawn text is a touch off the measured widths.
"""
import os

WINFONTS = r"C:\Windows\Fonts"
HERE = os.path.dirname(os.path.abspath(__file__))
METRICS_PATH = os.path.join(HERE, "font_metrics.json")
GAME_FONTS = os.path.join(HERE, "gamefiles", "fonts")


def _first(*names):
    for n in names:
        p = os.path.join(WINFONTS, n)
        if os.path.exists(p):
            return p
    return None


def font_key(path):
    """WoW font path -> key ('frizqt' | 'arialn' | 'morpheus' | 'skurri')."""
    p = (path or "").replace("/", "\\").lower()
    base = p.rsplit("\\", 1)[-1]
    if base.startswith("arialn"):
        return "arialn"
    if base.startswith("morpheus"):
        return "morpheus"
    if base.startswith("skurri"):
        return "skurri"
    return "frizqt"


def font_file(key):
    """key -> (ttf path, horizontal tracking factor). Real fonts have no tracking fudge."""
    real = os.path.join(GAME_FONTS, key + ".ttf")
    if os.path.exists(real):
        return real, 1.0
    if key == "arialn":
        narrow = _first("arialn.ttf", "ARIALN.TTF")
        if narrow:
            return narrow, 1.0
        return _first("arial.ttf", "segoeui.ttf"), 0.89  # calibrated vs in-game ARIALN
    if key in ("morpheus", "skurri"):
        return _first("georgiab.ttf", "georgia.ttf", "segoeuib.ttf"), 1.0
    return _first("georgia.ttf", "segoeui.ttf", "arial.ttf"), 1.10  # calibrated vs in-game FRIZQT


FONT_KEYS = ("frizqt", "arialn", "morpheus", "skurri")
