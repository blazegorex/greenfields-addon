"""Font mapping shared by render.py (system Python + PIL) and run.py (venv, no PIL).

WoW font paths are mapped onto Windows fonts:
    FRIZQT__ -> georgia.ttf (falls back to segoeui.ttf)
    ARIALN   -> arialn.ttf if present, else arial.ttf drawn with narrower tracking
    MORPHEUS -> georgiab.ttf
    SKURRI   -> georgiab.ttf
Anything else falls back to the FRIZQT stand-in.

`font_metrics.json` (generated by `render.py --metrics`) holds per-character advance
widths at size 100 for each stand-in, so the mock's GetStringWidth matches what the
renderer draws. run.py loads it when present and otherwise uses a flat estimate.
"""
import os

WINFONTS = r"C:\Windows\Fonts"
HERE = os.path.dirname(os.path.abspath(__file__))
METRICS_PATH = os.path.join(HERE, "font_metrics.json")


def _first(*names):
    for n in names:
        p = os.path.join(WINFONTS, n)
        if os.path.exists(p):
            return p
    return None


def font_key(path):
    """WoW font path -> stand-in key ('frizqt' | 'arialn' | 'morpheus')."""
    p = (path or "").replace("/", "\\").lower()
    base = p.rsplit("\\", 1)[-1]
    if base.startswith("arialn"):
        return "arialn"
    if base.startswith("morpheus") or base.startswith("skurri"):
        return "morpheus"
    return "frizqt"


def font_file(key):
    """stand-in key -> (ttf path, horizontal tracking factor)."""
    if key == "arialn":
        narrow = _first("arialn.ttf", "ARIALN.TTF")
        if narrow:
            return narrow, 1.0
        return _first("arial.ttf", "segoeui.ttf"), 0.89  # calibrated vs in-game ARIALN
    if key == "morpheus":
        return _first("georgiab.ttf", "georgia.ttf", "segoeuib.ttf"), 1.0
    return _first("georgia.ttf", "segoeui.ttf", "arial.ttf"), 1.10  # calibrated vs in-game FRIZQT


FONT_KEYS = ("frizqt", "arialn", "morpheus")
